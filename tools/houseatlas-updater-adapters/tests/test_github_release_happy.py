"""Two named generated positive cases through a finite in-process HTTPS model.

No socket, credentials, provider request, controller action or native executable.
Inspect the pinned packaging source before invoking these exact cases.
"""

import importlib.util
import json
import os
import tempfile
import time
import unittest
from contextlib import contextmanager
from pathlib import Path

from github_release import API, ASSET_ORIGIN, CHUNK, HEADER_LIMIT, GitHubReleaseAcquisition
from houseatlas_updater.model import Policy, Producer, Selection, Storage
from houseatlas_updater.release_bundle import FIXTURE_SHA256, SCHEMA_SHA256, ReleaseBundleV1, validate_schema
from houseatlas_updater.validation import sha256


def load_source(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def reviewed_packaging(test):
    source = Path(os.environ.get("HOUSEATLAS_PACKAGING_SOURCE",
                                str(Path(__file__).resolve().parents[2] / "release")))
    pins = {"bundle.py": "b215dac5ef4ef37607d2883cfb38c82f94d7cab3f6007e96679902ae35a535c4",
            "fixtures.py": "73cb43a2e183a5c6137d068cda43b24c471e2df2e38ade7a7089a12c7a8be8dc",
            "bundle.schema.json": SCHEMA_SHA256,
            "fixtures/bundle.manifest.json": FIXTURE_SHA256}
    for name, expected in pins.items():
        test.assertEqual(sha256((source / name).read_bytes()), expected)
    schema = (source / "bundle.schema.json").read_bytes()
    validate_schema(json.loads((source / "fixtures/bundle.manifest.json").read_bytes()), json.loads(schema))
    return (load_source(source / "bundle.py", "acquisition_reviewed_packager"),
            load_source(source / "fixtures.py", "acquisition_reviewed_fixtures"), schema)


class GeneratedHttp:
    """Every request resolves to finite generated bytes; no fallback transport."""

    def __init__(self, test):
        self.test = test
        self.routes = {}
        self.calls = []
        self.closed = 0
        self.reads = []
        self.deadline = None

    def metadata(self, path, value):
        self.routes[API + path] = (200, "application/json", json.dumps(value).encode(), {})

    @contextmanager
    def open(self, url, *, headers, deadline, max_header_bytes):
        test = self.test
        test.assertGreater(deadline, time.monotonic())
        test.assertEqual(max_header_bytes, HEADER_LIMIT)
        if self.deadline is None:
            self.deadline = deadline
        test.assertEqual(deadline, self.deadline)
        test.assertEqual(set(headers), {"accept", "accept-encoding", "user-agent"} |
                         ({"x-github-api-version"} if url.startswith(API) else set()))
        test.assertEqual(headers["accept-encoding"], "identity")
        status, content_type, body, extra = self.routes[url]
        test.assertEqual(headers["accept"], "application/vnd.github+json" if content_type ==
                         "application/json" else "application/octet-stream")
        self.calls.append(url)
        owner = self

        class Reply:
            def __init__(self):
                self.status = status
                self.headers = {"content-type": content_type, "content-length": str(len(body)), **extra}
                self.offset = 0

            def read(self, size, *, deadline):
                test.assertGreater(size, 0)
                test.assertLessEqual(size, CHUNK)
                test.assertEqual(deadline, owner.deadline)
                owner.reads.append(size)
                # Ordinary partial network reads, with a bounded maximum chunk.
                stop = min(self.offset + size, self.offset + 97, len(body))
                data = body[self.offset:stop]
                self.offset = stop
                return data

        try:
            yield Reply()
        finally:
            self.closed += 1


class GitHubReleaseHappyPaths(unittest.TestCase):
    def generated(self, root, *, annotated_redirect=False):
        packaging, fixtures, schema = reviewed_packaging(self)
        payload = fixtures.payload(root / "generated-software")
        metadata = fixtures.metadata()
        if not annotated_redirect:
            metadata["version"] = "1.2.3"
        # These are synthetic declarations and API replies, never real approvals.
        metadata["build"].update(kind="github-actions", runId="73", runAttempt=2)
        metadata["compatibility"].update(status="reviewed", requiredStorageContractSha256="4" * 64,
                                          resultingStorageContractSha256="4" * 64,
                                          codeRollbackCompatible=True)
        output = root / "generated-release"
        value = packaging.pack(payload, metadata, output)
        manifest = (output / "manifest.json").read_bytes()
        archive = (output / value["archive"]["name"]).read_bytes()
        selected = Selection(value["version"], value["source"]["commit"], value["source"]["tree"],
                             10, 20, value["archive"]["name"], sha256(archive), sha256(manifest))
        policy = Policy(root / "unused-staging", root / "unused-publication", root / "unused-journal",
                        (), "x86_64-apple-darwin", "15.0", ("apple-darwin",),
                        backend_entry="bin/houseatlas", bundle_contract="houseatlas.release-bundle.v1")
        storage = Storage("synthetic-receipt/1", "synthetic-config/1", 1, "synthetic-atlas", 1, 1)
        verifier = ReleaseBundleV1(schema, {"4" * 64: storage}, "3" * 64)
        http = GeneratedHttp(self)
        repository = {"id": 50, "full_name": policy.repository, "private": False,
                      "visibility": "public", "fork": False}
        http.metadata("", repository)
        rows = []
        for asset_id, name in ((20, selected.asset_name), (21, "manifest.json"), (22, "SHA256SUMS")):
            data = (output / name).read_bytes()
            rows.append({"id": asset_id, "name": name, "size": len(data), "state": "uploaded",
                         "digest": "sha256:" + sha256(data)})
            url = API + f"/releases/assets/{asset_id}"
            if annotated_redirect:
                location = ASSET_ORIGIN + f"/generated/{asset_id}?synthetic=finite"
                http.routes[url] = (302, "application/octet-stream", b"", {"location": location})
                url = location
            http.routes[url] = (200, "application/octet-stream", data, {})
        http.metadata("/releases/10", {"id": 10, "draft": False,
                                     "prerelease": "-" in selected.version,
                                     "published_at": "2026-10-18T00:00:00Z",
                                     "tag_name": "v" + selected.version, "assets": rows})
        tag_object = {"type": "commit", "sha": selected.commit}
        if annotated_redirect:
            http.metadata("/git/tags/" + "7" * 40, {"sha": "7" * 40, "object": tag_object})
            tag_object = {"type": "tag", "sha": "7" * 40}
        http.metadata("/git/ref/tags/v" + selected.version,
                      {"ref": "refs/tags/v" + selected.version, "object": tag_object})
        http.metadata("/git/commits/" + selected.commit,
                      {"sha": selected.commit, "tree": {"sha": selected.tree}})
        http.metadata("/actions/workflows/release-bundle.yml",
                      {"id": 60, "path": policy.workflow, "state": "active"})
        run = {"id": 73, "run_attempt": 2, "workflow_id": 60, "path": policy.workflow,
               "event": "workflow_dispatch", "head_branch": "main", "head_sha": selected.commit,
               "status": "completed", "conclusion": "success",
               "repository": repository, "head_repository": repository}
        http.metadata("/actions/runs/73", run)
        http.metadata("/actions/runs/73/attempts/2", run)
        http.metadata("/actions/runs/73/attempts/2/jobs?per_page=100",
                      {"total_count": 3, "jobs": [
                          {"name": "validate", "status": "completed", "conclusion": "success"},
                          {"name": "build", "run_id": 73, "run_attempt": 2, "head_sha": selected.commit,
                           "status": "completed", "conclusion": "success"},
                          {"name": "promote", "status": "completed", "conclusion": "skipped"}]})
        return http, selected, policy, verifier, manifest, archive, storage

    def exercise(self, *, annotated_redirect=False):
        with tempfile.TemporaryDirectory(prefix="houseatlas-acquisition-generated-") as scratch:
            root = Path(scratch)
            http, selected, policy, verifier, manifest, archive, storage = self.generated(
                root, annotated_redirect=annotated_redirect)
            acquired = GitHubReleaseAcquisition(http, verifier).acquire(selected, policy)
            self.assertEqual(acquired.selection, selected)
            self.assertEqual(acquired.manifest, manifest)
            self.assertEqual(acquired.archive, archive)
            self.assertEqual(acquired.producer, Producer(policy.repository, policy.workflow, policy.source_ref,
                                                        selected.commit, selected.tree, 73, 2))
            bundle = verifier.verify(acquired, policy)
            self.assertEqual(bundle.storage, storage)
            self.assertEqual(bundle.contract, "houseatlas.release-bundle.v1")
            self.assertEqual(bundle.shell_identity, "a" * 64)
            self.assertEqual(http.closed, len(http.calls))
            self.assertEqual(len(http.calls), 18 if annotated_redirect else 13)
            self.assertGreater(len(http.reads), len(http.calls))
            self.assertEqual(http.calls.count(API + "/releases/10"), 2)
            self.assertEqual(http.calls.count(API + "/git/ref/tags/v" + selected.version), 2)
            self.assertFalse(policy.staging_parent.exists())
            self.assertFalse(policy.publication_root.exists())
            self.assertFalse(policy.journal_directory.exists())

    def test_published_release_exact_build_and_bytes(self):
        self.exercise()

    def test_annotated_prerelease_bounded_asset_redirects(self):
        self.exercise(annotated_redirect=True)
