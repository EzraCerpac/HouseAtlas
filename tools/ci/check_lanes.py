# Restricted workflow reader --------------------------------------------------

class Scalar:
    def __init__(self, text, style, line, comment=False):
        self.text, self.style, self.line, self.comment = text, style, line, comment


class Block:
    def __init__(self, style, lines, line):
        self.style, self.lines, self.line = style, lines, line


KEY_LINE = re.compile(r'([A-Za-z0-9_.-]+|<<):(?: (.*))?$')
BLOCK_HEADER = re.compile(r'[|>][-+0-9]*')


class Reader:
    def __init__(self, name, text):
        self.name = name
        if '\t' in text:
            line = text[:text.index('\t')].count('\n') + 1
            raise LaneError(f'{name}:{line}: tab character')
        self.lines = text.split('\n')
        self.pos = 0

    def fail(self, line, message):
        raise LaneError(f'{self.name}:{line}: {message}')

    def peek(self):
        """Next structural line as (index, indent, content), skipping blanks and comments."""
        index = self.pos
        while index < len(self.lines):
            raw = self.lines[index]
            stripped = raw.strip()
            if stripped and not stripped.startswith('#'):
                return index, len(raw) - len(raw.lstrip(' ')), stripped
            index += 1
        return None

    def document(self):
        first = self.peek()
        if first is None or first[1] != 0:
            self.fail(1 if first is None else first[0] + 1, 'expected a top-level mapping')
        value = self.node(0)
        rest = self.peek()
        if rest is not None:
            self.fail(rest[0] + 1, 'unexpected indentation')
        return value

    def node(self, indent):
        head = self.peek()
        if head[2] == '-' or head[2].startswith('- '):
            return self.sequence(indent)
        return self.mapping(indent)

    def sequence(self, indent):
        items = []
        while True:
            head = self.peek()
            if head is None or head[1] < indent:
                return items
            index, found, content = head
            if found != indent:
                self.fail(index + 1, 'unexpected indentation')
            if not (content == '-' or content.startswith('- ')):
                self.fail(index + 1, 'mapping key inside a sequence')
            raw = self.lines[index]
            # Re-read "- key: value" as a mapping indented past the dash.
            self.lines[index] = raw[:indent] + ' ' + raw[indent + 1:]
            inner = self.peek()
            if inner[0] != index:
                self.fail(index + 1, 'empty sequence item')
            if KEY_LINE.match(inner[2]):
                items.append(self.mapping(inner[1]))
            else:
                self.pos = index + 1
                items.append(self.scalar(inner[2], index + 1))

    def mapping(self, indent):
        result = {}
        while True:
            head = self.peek()
            if head is None or head[1] < indent:
                return result
            index, found, content = head
            if found != indent:
                self.fail(index + 1, 'unexpected indentation')
            if content == '-' or content.startswith('- '):
                self.fail(index + 1, 'sequence item inside a mapping')
            match = KEY_LINE.match(content)
            if not match:
                self.fail(index + 1, 'expected "key: value"')
            key, value = match.group(1), (match.group(2) or '').strip()
            if key == '<<':
                self.fail(index + 1, 'merge key')
            if key in result:
                self.fail(index + 1, f'duplicate key {key}')
            self.pos = index + 1
            if value == '' or value.startswith('#'):
                child = self.peek()
                if child is not None and child[1] > indent:
                    result[key] = self.node(child[1])
                elif child is not None and child[1] == indent and child[2].startswith('-'):
                    self.fail(child[0] + 1, 'sequence at its key indentation')
                else:
                    result[key] = None
            elif BLOCK_HEADER.fullmatch(value.split(' #')[0].strip()):
                result[key] = self.block(value.split(' #')[0].strip(), indent, index + 1)
            else:
                result[key] = self.scalar(value, index + 1)
                child = self.peek()
                if child is not None and child[1] > indent:
                    self.fail(child[0] + 1, 'multi-line plain scalar or unexpected indentation')
        return result

    def scalar(self, value, line):
        if value[0] in '&*!':
            self.fail(line, 'anchor, alias or tag')
        if value[0] in '\'"':
            return Scalar(value, 'quoted', line)
        if value[0] in '[{':
            return Scalar(value, 'flow', line)
        if value[0] in '|>%@`':
            self.fail(line, f'unsupported scalar {value[:12]!r}')
        text, comment = value, False
        cut = re.search(r'\s#', value)
        if cut:
            text, comment = value[:cut.start()].rstrip(), True
        if ': ' in text or text.endswith(':'):
            self.fail(line, 'plain scalar containing ": "')
        return Scalar(text, 'plain', line, comment)

    def block(self, header, indent, line):
        if header not in ('|', '>-'):
            self.fail(line, f'block scalar style {header!r}; only | and >- are read')
        raw = []
        while self.pos < len(self.lines):
            text = self.lines[self.pos]
            if text.strip() and len(text) - len(text.lstrip(' ')) <= indent:
                break
            raw.append(text)
            self.pos += 1
        while raw and not raw[-1].strip():
            raw.pop()
        if not raw or not raw[0].strip():
            self.fail(line, 'empty or blank-led block scalar')
        depth = len(raw[0]) - len(raw[0].lstrip(' '))
        lines = []
        for offset, text in enumerate(raw):
            if text.strip() and len(text) - len(text.lstrip(' ')) < depth:
                self.fail(line + 1 + offset, 'block scalar line below its indentation')
            lines.append(text[depth:] if text.strip() else '')
        if header == '>-':
            for offset, text in enumerate(lines):
                if not text or text[0] == ' ':
                    self.fail(line + 1 + offset, 'blank or more-indented line in a >- block')
            lines = [' '.join(lines)]
        return Block(header, lines, line)


def plain(name, value, what, optional=False):
    if value is None and optional:
        return None
    if not isinstance(value, Scalar) or value.style != 'plain' or value.comment:
        line = getattr(value, 'line', '?')
        raise LaneError(f'{name}:{line}: {what} must be an uncommented plain scalar')
    return value.text


def unquoted(name, value, what):
    """Plain uncommented or single/double-quoted text (no escapes)."""
    if isinstance(value, Scalar) and value.style == 'quoted':
        text, quote = value.text, value.text[0]
        inner = text[1:-1]
        if len(text) < 2 or text[-1] != quote or (quote == '"' and ('\\' in inner or '"' in inner)) \
                or (quote == "'" and "'" in inner.replace("''", '')):
            raise LaneError(f'{name}:{value.line}: {what} must be one quoted value without escapes or a comment')
        return inner.replace("''", "'") if quote == "'" else inner
    return plain(name, value, what)


def env_map(name, value, what):
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise LaneError(f'{name}: {what} env must be a mapping')
    return {key: unquoted(name, item, f'{what} env {key}') for key, item in value.items()}


def normalized(name, value):
    """Plain JSON form of a read value: scalars as text (flow values verbatim), blocks as joined lines."""
    if value is None:
        return None
    if isinstance(value, dict):
        return {key: normalized(name, item) for key, item in value.items()}
    if isinstance(value, list):
        return [normalized(name, item) for item in value]
    if isinstance(value, Block):
        return '\n'.join(value.lines)
    if value.style == 'quoted':
        return unquoted(name, value, 'value')
    if value.comment:
        raise LaneError(f'{name}:{value.line}: trailing comment on a compared value')
    return value.text


def unread(name, mapping, allowed, what):
    for key in mapping:
        if key not in allowed:
            raise LaneError(f'{name}: {what} key {key!r} is not read by this checker')


def read_steps(name, owner, steps):
    if not isinstance(steps, list):
        raise LaneError(f'{name}: {owner} has no steps list')
    result, seen = [], set()
    for step in steps:
        if not isinstance(step, dict):
            raise LaneError(f'{name}: {owner} has a non-mapping step')
        if 'run' not in step:
            continue
        run = step['run']
        if 'name' not in step:
            raise LaneError(f'{name}:{getattr(run, "line", "?")}: unnamed run step in {owner}')
        title = plain(name, step['name'], 'step name')
        unread(name, step, READ_RUN_STEP_KEYS, f'run step {title!r}')
        if title in seen:
            raise LaneError(f'{name}: duplicate step name {title!r} in {owner}')
        seen.add(title)
        if isinstance(run, Block):
            lines = run.lines
        else:
            lines = [plain(name, run, f'run of {title!r}')]
        result.append({
            'step': title,
            # Later steps' conditions name this id (steps.<id>.outputs), so it is compared too.
            'stepId': plain(name, step.get('id'), f'id of {title!r}', optional=True),
            'if': plain(name, step.get('if'), f'if of {title!r}', optional=True),
            'run': lines,
            'env': env_map(name, step.get('env'), title),
            'options': {key: normalized(name, step[key]) for key in STEP_OPTIONS if key in step},
        })
    return result


def read_workflow(name, text):
    """Returns the workflow name, triggers, env and, per job, its selection fields and run steps."""
    tree = Reader(name, text).document()
    if not isinstance(tree, dict) or not isinstance(tree.get('jobs'), dict):
        raise LaneError(f'{name}: missing jobs mapping')
    unread(name, tree, READ_WORKFLOW_KEYS, 'workflow')
    workflow = {
        'name': plain(name, tree.get('name'), 'workflow name', optional=True),
        'on': normalized(name, tree.get('on')),
        'env': env_map(name, tree.get('env'), 'workflow'),
        'jobs': {},
    }
    for job_id, job in tree['jobs'].items():
        if not isinstance(job, dict):
            raise LaneError(f'{name}: job {job_id} must be a mapping')
        unread(name, job, READ_JOB_KEYS, f'job {job_id}')
        strategy = job.get('strategy')
        if strategy is not None and not isinstance(strategy, dict):
            raise LaneError(f'{name}: job {job_id} strategy must be a mapping')
        unread(name, strategy or {}, READ_STRATEGY_KEYS, f'job {job_id} strategy')
        matrix = (strategy or {}).get('matrix')
        if matrix is not None and not isinstance(matrix, dict):
            raise LaneError(f'{name}: job {job_id} matrix must be a mapping')
        record = {
            'runsOn': plain(name, job.get('runs-on'), f'{job_id} runs-on'),
            'if': plain(name, job.get('if'), f'{job_id} if', optional=True),
            'matrix': None if matrix is None else {
                key: getattr(item, 'text', None) for key, item in matrix.items()},
            'needs': normalized(name, job.get('needs')),
            'env': env_map(name, job.get('env'), f'job {job_id}'),
            'steps': read_steps(name, f'job {job_id}', job.get('steps')),
        }
        if record['matrix'] is not None and None in record['matrix'].values():
            raise LaneError(f'{name}: job {job_id} matrix values must be one-line scalars')
        workflow['jobs'][job_id] = record
    return workflow


def read_action(name, text):
    """Returns a composite action's name and run steps as one pseudo-job named runs."""
    tree = Reader(name, text).document()
    if not isinstance(tree, dict):
        raise LaneError(f'{name}: expected a top-level mapping')
    unread(name, tree, READ_ACTION_KEYS, 'action')
    runs = tree.get('runs')
    if not isinstance(runs, dict) or getattr(runs.get('using'), 'text', None) != 'composite':
        raise LaneError(f'{name}: only composite actions are read')
    unread(name, runs, {'using', 'steps'}, 'action runs')
    return {'name': plain(name, tree.get('name'), 'action name', optional=True),
            'jobs': {ACTION_JOB: {'steps': read_steps(name, 'the composite action', runs.get('steps'))}}}


# Case counters ----------------------------------------------------------------

def unittest_methods(path):
    tree = ast.parse(path.read_text(encoding='utf-8'), str(path))
    count = 0
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and any(
                (isinstance(base, ast.Attribute) and base.attr == 'TestCase')
                or (isinstance(base, ast.Name) and base.id == 'TestCase') for base in node.bases):
            count += sum(1 for item in node.body
                         if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
                         and item.name.startswith('test'))
    return count


def argparse_choices(path):
    """Evaluates module-level string-tuple names and the one choices= expression."""
    tree = ast.parse(path.read_text(encoding='utf-8'), str(path))
    names = {}

    def evaluate(node):
        if isinstance(node, ast.Tuple) and all(
                isinstance(item, ast.Constant) and isinstance(item.value, str) for item in node.elts):
            return tuple(item.value for item in node.elts)
        if isinstance(node, ast.Name) and node.id in names:
            return names[node.id]
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            return evaluate(node.left) + evaluate(node.right)
        raise LaneError(f'{path}: unsupported choices expression at line {node.lineno}')

    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                names[node.targets[0].id] = evaluate(node.value)
            except LaneError:
                pass
        elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name) and node.target.id in names:
            names[node.target.id] = names[node.target.id] + evaluate(node.value)
    found = [keyword.value for node in ast.walk(tree) if isinstance(node, ast.Call)
             for keyword in node.keywords if keyword.arg == 'choices']
    if len(found) != 1:
        raise LaneError(f'{path}: expected exactly one choices= argument, found {len(found)}')
    return set(evaluate(found[0]))


def run_healthy_lists(path):
    """Counts entries in the SOURCE/BUILD/BROWSER arrays; anything unrecognized is refused."""
    text = path.read_text(encoding='utf-8')
    counts, files = {}, []
    for name in RUN_HEALTHY_LISTS:
        found = re.findall(r'^const %s = \[(.*?)\];[ \t]*$' % name, text, re.S | re.M)
        if len(found) != 1:
            raise LaneError(f'{path}: expected one const {name} list')
        body = re.sub(r'//[^\n]*', '', found[0])
        count = 0
        for match in re.finditer(r"\.\.\.cases\('([^']+)', '[^']*', \[([^\]]*)\]\)", body):
            files.append('frontend/lantern-tests/' + match.group(1))
            names = re.findall(r"'([^']+)'", match.group(2))
            if not names:
                raise LaneError(f'{path}: empty cases() list in {name}')
            count += len(names)
        body = re.sub(r"\.\.\.cases\('[^']+', '[^']*', \[[^\]]*\]\)", '', body)
        for match in re.finditer(r"\bnode\('([^']+)'(?:, '[^']*')*\)", body):
            files.append('frontend/lantern-tests/' + match.group(1))
            count += 1
        body = re.sub(r"\bnode\('[^']+'(?:, '[^']*')*\)", '', body)
        for match in re.finditer(r"\['([^']+)'(?:, '[^']*')*\]", body):
            files.append(match.group(1))
            count += 1
        body = re.sub(r"\['[^']+'(?:, '[^']*')*\]", '', body)
        if body.replace(',', '').strip():
            raise LaneError(f'{path}: unrecognized {name} entry {body.replace(",", "").split()[0][:40]!r}')
        counts[name] = count
    return counts, files


