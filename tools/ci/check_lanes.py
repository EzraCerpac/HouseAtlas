def squash(text):
    return ' '.join(text.split())


def safe_path(root, relative, errors, where):
    if (not isinstance(relative, str) or not relative or relative.startswith('/')
            or any(part in ('', '.', '..') for part in relative.split('/'))):
        errors.append(f'{where}: invalid repository path {relative!r}')
        return None
    path = root / relative
    if not path.is_file():
        errors.append(f'{where}: missing file {relative}')
        return None
    return path


def check_cases(root, row, errors):
    where = f"step {row['id']}"
    cases = row['cases']
    counter = cases.get('counter') if isinstance(cases, dict) else None
    if counter not in COUNTER_KEYS:
        errors.append(f'{where}: unknown case counter {counter!r}')
        return
    if set(cases) - {'counter'} != COUNTER_KEYS[counter]:
        errors.append(f'{where}: {counter} takes exactly {sorted(COUNTER_KEYS[counter])}')
        return
    run = '\n'.join(row['run'])
    expected = cases['expected']
    try:
        if counter == 'python-unittest-methods':
            directory, pattern = cases['dir'], cases['pattern']
            if not re.search(r'-s %s -p \'?%s\'?(?:\s|$)' % (re.escape(directory), re.escape(pattern)), run):
                errors.append(f'{where}: run does not discover -s {directory} -p {pattern}')
                return
            base = root / directory
            matched = sorted(path for path in base.iterdir()
                             if path.is_file() and fnmatch.fnmatchcase(path.name, pattern)) if base.is_dir() else []
            if not matched:
                errors.append(f'{where}: no file in {directory} matches {pattern}')
                return
            for path in matched:
                if path.relative_to(root).as_posix() not in row['files']:
                    errors.append(f'{where}: discovered {path.relative_to(root).as_posix()} is not in files')
            actual = sum(unittest_methods(path) for path in matched)
        elif counter == 'python-argparse-choices':
            path = safe_path(root, cases['file'], errors, where)
            if path is None:
                return
            choices = argparse_choices(path)
            invocations = [line.split()[-1] for line in row['run'] if cases['file'] in line]
            for name in invocations:
                if name not in choices:
                    errors.append(f'{where}: {name!r} is not an argparse choice in {cases["file"]}')
            actual = len(invocations)
        elif counter == 'node-test-toplevel':
            actual = 0
            for relative in cases['files']:
                if relative not in run:
                    errors.append(f'{where}: counted file {relative} is not in run')
                path = safe_path(root, relative, errors, where)
                if path is not None:
                    actual += len(re.findall(r'^test\(', path.read_text(encoding='utf-8'), re.M))
        elif counter == 'run-healthy-list':
            if cases['file'] not in run:
                errors.append(f'{where}: counted file {cases["file"]} is not in run')
            path = safe_path(root, cases['file'], errors, where)
            if path is None:
                return
            actual, listed = run_healthy_lists(path)
            for relative in sorted(set(listed)):
                safe_path(root, relative, errors, f'{where} list entry')
        else:
            actual = run.split().count('--skip')
    except (LaneError, SyntaxError, OSError, UnicodeError) as error:
        errors.append(f'{where}: {error}')
        return
    if actual != expected:
        errors.append(f'{where}: {counter} counts {actual}, manifest expects {expected}')


def run_difference(workflow, manifest):
    if not isinstance(manifest, list):
        return '; manifest run must be a list of lines'
    for index, (left, right) in enumerate(zip(workflow, manifest)):
        if left != right:
            return f' at line {index + 1}\n  workflow: {left!r}\n  manifest: {right!r}'
    return f'; workflow has {len(workflow)} lines, manifest has {len(manifest)}'


def source(key):
    """Repository path of a workflow or action key."""
    return f'{ACTIONS}/{key}' if key.endswith('/action.yml') else f'{WORKFLOWS}/{key}'


def check(root, manifest, workflows, docs_text, actions=None):
    """Returns (errors, rendered block or None). workflows and actions map file keys to text."""
    errors = []
    actions = {} if actions is None else actions
    if not isinstance(manifest, dict) or manifest.get('format') != FORMAT:
        return [f'{MANIFEST}: format must be {FORMAT}'], None
    if set(manifest) != TOP_KEYS:
        return [f'{MANIFEST}: top-level keys must be exactly {sorted(TOP_KEYS)}'], None
    toolchains, lanes = manifest['toolchains'], manifest['lanes']
    in_scope, out_scope = manifest['workflows'], manifest['outOfScopeWorkflows']
    action_specs = manifest['actions']

    for name, chain in toolchains.items():
        if not isinstance(chain, dict) or set(chain) != {'version', 'pins'}:
            errors.append(f'toolchain {name}: keys must be version and pins')
            continue
        for pin in chain['pins']:
            path = safe_path(root, pin[0], errors, f'toolchain {name}')
            if path is not None and pin[1] not in path.read_text(encoding='utf-8'):
                errors.append(f'toolchain {name}: {pin[0]} lacks {pin[1]!r}')
            if chain['version'] is not None and chain['version'] not in pin[1]:
                errors.append(f'toolchain {name}: pin {pin[1]!r} does not name {chain["version"]}')
        if chain['version'] is not None and not chain['pins']:
            errors.append(f'toolchain {name}: a version needs at least one pin')

    for name, lane in lanes.items():
        if not isinstance(lane, dict) or set(lane) != {'runLane', 'when'} or not lane['when']:
            errors.append(f'lane {name}: keys must be runLane and a non-empty when')

    present = set(workflows)
    for name in sorted(set(in_scope) & set(out_scope)):
        errors.append(f'workflow {name} is both in and out of scope')
    for name in sorted(present - set(in_scope) - set(out_scope)):
        errors.append(f'{WORKFLOWS}/{name} is not listed in {MANIFEST}')
    for name in sorted((set(in_scope) | set(out_scope)) - present):
        errors.append(f'{MANIFEST} lists missing workflow {WORKFLOWS}/{name}')
    for name, reason in out_scope.items():
        if not isinstance(reason, str) or not reason.strip():
            errors.append(f'out-of-scope workflow {name} needs a reason')
    for name in sorted(set(actions) - set(action_specs)):
        errors.append(f'{ACTIONS}/{name} is not listed in {MANIFEST} actions')
    for name in sorted(set(action_specs) - set(actions)):
        errors.append(f'{MANIFEST} lists missing action {ACTIONS}/{name}')

    parsed, used_lanes, lane_jobs = {}, set(), set()
    for name in sorted(set(action_specs) & set(actions)):
        if not name.endswith('/action.yml') or name.count('/') != 1:
            errors.append(f'action {name}: key must be <directory>/action.yml')
            continue
        try:
            parsed[name] = read_action(source(name), actions[name])
        except LaneError as error:
            errors.append(str(error))
            continue
        if action_specs[name] != {'name': parsed[name]['name']}:
            errors.append(f'action {name}: manifest must be exactly {{"name": {parsed[name]["name"]!r}}}')
    for name in sorted(set(in_scope) & present):
        try:
            parsed[name] = read_workflow(f'{WORKFLOWS}/{name}', workflows[name])
        except LaneError as error:
            errors.append(str(error))
            continue
        spec, actual = in_scope[name], parsed[name]
        if set(spec) != WORKFLOW_KEYS:
            errors.append(f'workflow {name}: keys must be {sorted(WORKFLOW_KEYS)}')
            continue
        for key in ('name', 'on', 'env'):
            if spec[key] != actual[key]:
                errors.append(f'workflow {name}: {key} is {actual[key]!r}, manifest says {spec[key]!r}')
        for job in sorted(set(actual['jobs']) ^ set(spec['jobs'])):
            errors.append(f'workflow {name}: job {job} is {"unlisted" if job in actual["jobs"] else "stale"}')
        for job, job_spec in spec['jobs'].items():
            if job not in actual['jobs']:
                continue
            got = actual['jobs'][job]
            if set(job_spec) != JOB_KEYS:
                errors.append(f'{name} job {job}: keys must be {sorted(JOB_KEYS)}')
                continue
            for key in ('runsOn', 'if', 'matrix', 'needs', 'env'):
                if job_spec[key] != got[key]:
                    errors.append(f'{name} job {job}: {key} is {got[key]!r}, manifest says {job_spec[key]!r}')
            selectors = [step['env']['RUN_LANE'] for step in got['steps'] if 'RUN_LANE' in step['env']]
            lane = job_spec['lane']
            if lane is None:
                if selectors:
                    errors.append(f'{name} job {job}: has a RUN_LANE selector but no manifest lane')
            elif lane not in lanes:
                errors.append(f'{name} job {job}: unknown lane {lane!r}')
            else:
                used_lanes.add(lane)
                lane_jobs.add((name, job))
                if selectors != [lanes[lane]['runLane']]:
                    errors.append(f'{name} job {job}: RUN_LANE {selectors!r} differs from lane {lane}')
    if len(parsed) == len(set(in_scope) & present) + len(set(action_specs) & set(actions)):
        for name in sorted(set(lanes) - used_lanes):
            errors.append(f'lane {name} is used by no job')

    rows, ids = {}, set()
    for index, row in enumerate(manifest['steps']):
        where = f'steps[{index}]'
        if not isinstance(row, dict) or not ROW_KEYS <= set(row) <= ROW_KEYS | ROW_OPTIONAL:
            errors.append(f'{where}: keys must be {sorted(ROW_KEYS)} plus optional {sorted(ROW_OPTIONAL)}')
            continue
        where = f"step {row['id']}"
        if not re.fullmatch(r'[a-z0-9][a-z0-9.-]*', str(row['id'])) or row['id'] in ids:
            errors.append(f'{where}: id must be unique lowercase dotted text')
        ids.add(row['id'])
        if row['kind'] not in KINDS:
            errors.append(f'{where}: kind must be one of {", ".join(KINDS)}')
        if not isinstance(row['scope'], str) or not row['scope'].strip():
            errors.append(f'{where}: scope sentence is empty')
        key = (row['workflow'], row['job'], row['step'])
        if key in rows:
            errors.append(f'{where}: duplicates step {row["step"]!r} of {row["workflow"]} {row["job"]}')
        rows[key] = row

    actual_steps = {}
    for name, workflow in parsed.items():
        for job, record in workflow['jobs'].items():
            for step in record['steps']:
                actual_steps[(name, job, step['step'])] = step
    for key in sorted(set(actual_steps) - set(rows)):
        errors.append(f'{source(key[0])} job {key[1]}: run step {key[2]!r} has no {MANIFEST} row')
    for key in sorted(set(rows) - set(actual_steps)):
        if key[0] in parsed:
            errors.append(f'step {rows[key]["id"]}: stale row; {key[0]} job {key[1]} has no run step {key[2]!r}')

    for key, row in rows.items():
        if key not in actual_steps:
            continue
        where = f"step {row['id']}"
        step = actual_steps[key]
        if row['run'] != step['run']:
            errors.append(f'{where}: run differs from the workflow{run_difference(step["run"], row["run"])}')
        if row['if'] != step['if']:
            errors.append(f'{where}: if is {step["if"]!r}, manifest says {row["if"]!r}')
        if row.get('stepId') != step['stepId']:
            errors.append(f'{where}: step id is {step["stepId"]!r}, manifest says {row.get("stepId")!r}')
        # A lane job's RUN_LANE is compared with its lane above; every other env value is compared here.
        env = {name: value for name, value in step['env'].items()
               if not (name == 'RUN_LANE' and key[:2] in lane_jobs)}
        if row.get('env', {}) != env:
            errors.append(f'{where}: env is {env!r}, manifest says {row.get("env", {})!r}')
        if row.get('options', {}) != step['options']:
            errors.append(f'{where}: step options are {step["options"]!r}, manifest says {row.get("options", {})!r}')
        if key[1] == ACTION_JOB and key[0].endswith('/action.yml') and row['kind'] in SHOWN:
            errors.append(f'{where}: composite action steps take kind setup, plumbing or summary')
        declared = set(row['toolchain'])
        for chain in sorted(declared - set(toolchains)):
            errors.append(f'{where}: unknown toolchain {chain}')
        detected = {chain for chain, pattern in DETECT.items()
                    if any(pattern.search(line) for line in step['run'])}
        if 'HOUSEATLAS_CHROMIUM' in step['env']:
            detected.add('chromium')
        for chain in sorted(detected - declared):
            errors.append(f'{where}: uses {chain} but its toolchain list omits it')
        for relative in row['files']:
            safe_path(root, relative, errors, where)
        for relative in sorted(set(PATH_TOKEN.findall('\n'.join(step['run'])))):
            if relative not in row['files']:
                errors.append(f'{where}: run names {relative} but files omits it')
        if 'cases' in row:
            check_cases(root, row, errors)
        for claim in row.get('claims', []):
            if not (isinstance(claim, list) and len(claim) == 2):
                errors.append(f'{where}: a claim is [file, substring]')
                continue
            path = safe_path(root, claim[0], errors, f'{where} claim')
            if path is not None and squash(claim[1]) not in squash(path.read_text(encoding='utf-8')):
                errors.append(f'{where}: {claim[0]} no longer says {claim[1]!r}')

    if errors:
        return errors, None
    rendered = render(manifest)
    errors.extend(docs_errors(docs_text, rendered))
    return errors, rendered


# Generated inventory -----------------------------------------------------------

def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def code(text):
    return '`' + cell(text) + '`'


def runs_when(manifest, row):
    job = manifest['workflows'][row['workflow']]['jobs'][row['job']]
    parts = [f"{job['lane']} lane" if job['lane'] else 'every run']
    condition = row['if']
    if condition and condition.startswith(LANE_GUARD) and job['lane']:
        condition = condition[len(LANE_GUARD):].strip()
        if condition.startswith('&& (') and condition.endswith(')'):
            condition = condition[4:-1]
    for key, value in (job['matrix'] or {}).items():
        if f'matrix.{key}' not in (condition or ''):
            parts.append(f'matrix {key} {value}')
    if condition:
        parts.append(code(condition))
    for key, value in row.get('options', {}).items():
        parts.append(code(f'{key}: {value}'))
    return '; '.join(parts)


def triggers(on):
    events = []
    for event, config in (on or {}).items():
        if isinstance(config, dict) and config:
            event += ' (' + ', '.join(f'{key} {value}' for key, value in config.items()) + ')'
        events.append(event)
    return ', '.join(events)


def cases_text(cases):
    expected = cases['expected']
    counter = cases['counter']
    if counter == 'run-healthy-list':
        return ', '.join(f'{expected[name]} {name.lower()}' for name in RUN_HEALTHY_LISTS)
    if counter == 'cargo-skip':
        return f'default set, {expected} skipped'
    unit = {'python-unittest-methods': 'unittest methods', 'python-argparse-choices': 'named cases',
            'node-test-toplevel': 'top-level tests'}[counter]
    return f'{expected} {unit}'


def render(manifest):
    out = [BEGIN, '',
           '| Workflow / job | Step | Command | Runs when | Cases | Scope |',
           '| --- | --- | --- | --- | --- | --- |']
    hidden = in_actions = 0
    for row in manifest['steps']:
        if row['kind'] not in SHOWN:
            hidden += 1
            in_actions += row['workflow'] in manifest['actions']
            continue
        out.append('| ' + ' | '.join([
            f"{row['workflow'].rsplit('.', 1)[0]} / {row['job']}",
            cell(row['step']),
            '<br>'.join([code(f'{name}={value}') for name, value in row.get('env', {}).items()]
                        + [code(line) for line in row['run'] if line.strip()]),
            runs_when(manifest, row),
            cases_text(row['cases']) if 'cases' in row else '',
            cell(row['scope']),
        ]) + ' |')
    chains = []
    for name, chain in manifest['toolchains'].items():
        chains.append(f"`{name}` {chain['version']}" if chain['version'] else f'`{name}` (runner-provided, unpinned)')
    out += ['', f'{hidden} setup, plumbing and summary run steps ({in_actions} of them in composite actions under '
                f'`{ACTIONS}`) are listed in `{MANIFEST}` and omitted here. Commands show step env values first.']
    out.append('Triggers: ' + '; '.join(
        f"`{name}` on {triggers(spec['on'])}" for name, spec in manifest['workflows'].items()) + '.')
    if manifest['lanes']:
        out.append(' '.join(f"The {name} lane {lane['when']}." for name, lane in manifest['lanes'].items()))
    out += ['Toolchains: ' + ', '.join(chains) + '.',
            'Not ordinary scope: ' + '; '.join(
                f'`{name}` ({reason})' for name, reason in sorted(manifest['outOfScopeWorkflows'].items())) + '.',
            '', END]
    return '\n'.join(out)


def docs_errors(text, rendered):
    if text is None:
        return [f'{DOCS} is missing']
    starts, ends = text.count(BEGIN), text.count(END)
    if starts != 1 or ends != 1 or text.index(BEGIN) > text.index(END):
        return [f'{DOCS}: expected one generated block between {BEGIN!r} and {END!r}']
    start = text.index(BEGIN)
    if text[start:text.index(END) + len(END)] != rendered:
        return [f'{DOCS}: generated CI inventory is stale; run python3 -B -I tools/ci/check_lanes.py --write']
    return []


def replace_block(text, rendered):
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + rendered + text[end:]


def load(root):
    manifest = json.loads((root / MANIFEST).read_text(encoding='utf-8'))
    workflows = {path.name: path.read_text(encoding='utf-8')
                 for path in sorted((root / WORKFLOWS).iterdir()) if path.is_file()}
    base = root / ACTIONS
    actions = {path.relative_to(base).as_posix(): path.read_text(encoding='utf-8')
               for path in sorted(base.rglob('*')) if path.is_file()} if base.is_dir() else {}
    docs = root / DOCS
    return manifest, workflows, actions, docs.read_text(encoding='utf-8') if docs.is_file() else None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='report mismatches only (default)')
    mode.add_argument('--write', action='store_true', help='regenerate the verification-guide block')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        manifest, workflows, actions, docs = load(root)
    except (OSError, UnicodeError, ValueError) as error:
        print(f'check_lanes: cannot read inputs: {error}', file=sys.stderr)
        return 2
    try:
        errors, rendered = check(root, manifest, workflows, docs, actions)
    except (AttributeError, IndexError, KeyError, TypeError) as error:
        errors, rendered = [f'{MANIFEST}: malformed manifest ({type(error).__name__}: {error})'], None
    if args.write and rendered is not None:
        others = [error for error in errors if not error.startswith(f'{DOCS}: generated CI inventory is stale')]
        if not others:
            updated = replace_block(docs, rendered)
            if updated != docs:
                (root / DOCS).write_text(updated, encoding='utf-8')
            print(f'check_lanes: {DOCS} inventory {"rewritten" if updated != docs else "already current"}')
            errors = []
        else:
            errors = others
    for error in errors:
        print(f'check_lanes: {error}', file=sys.stderr)
    if errors:
        return 1
    if not args.write:
        print(f'check_lanes: {len(manifest["steps"])} rows match the run steps of '
              f'{len(manifest["workflows"])} workflows and {len(manifest["actions"])} composite actions; '
              'inventory current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
