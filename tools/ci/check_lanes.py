#!/usr/bin/env python3
"""Checks tools/ci/lanes.json against the ordinary CI workflows and composite actions.

Stdlib only (Python 3.9+). Reads repository files; no network, subprocess or
listed command runs. --check (default) reports every mismatch and changes
nothing. --write rewrites only the generated block in the verification guide,
and only when every other check passes.

  python3 -B -I tools/ci/check_lanes.py [--check | --write] [--root DIR]

The workflow reader accepts the small YAML subset these workflows use and
refuses anything else: tabs, anchors, aliases, tags, merge keys, block scalars
other than | and >-, multi-line plain scalars, quoted, flow or commented
name/if/run values, flow or commented env values, and workflow, job or run-step
keys it does not read (such as defaults, container or a run step's uses).
"""
