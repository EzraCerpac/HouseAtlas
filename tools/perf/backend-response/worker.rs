//! Supplemental single-threaded allocation observations; never linked into the server.
use houseatlas_backend::domain as d;
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
#[cfg(feature = "allocation-counts")]
use std::{
    alloc::{GlobalAlloc, Layout, System},
    cell::Cell,
};
use std::{hint::black_box, time::Instant};

#[cfg(feature = "allocation-counts")]
thread_local! {
    static COUNT: Cell<Option<(usize, usize)>> = const { Cell::new(None) };
}
#[cfg(feature = "allocation-counts")]
struct Counting;
#[cfg(feature = "allocation-counts")]
fn record(bytes: usize) {
    COUNT.with(|count| {
        if let Some((calls, total)) = count.get() {
            count.set(Some((calls + 1, total + bytes)));
        }
    });
}
// The standalone observer delegates the unchanged layout/pointer contract to
// System. Counters contain requested bytes, not allocator overhead or peak RSS.
#[cfg(feature = "allocation-counts")]
unsafe impl GlobalAlloc for Counting {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        record(layout.size());
        unsafe { System.alloc(layout) }
    }
    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        record(layout.size());
        unsafe { System.alloc_zeroed(layout) }
    }
    unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, size: usize) -> *mut u8 {
        record(size);
        unsafe { System.realloc(ptr, layout, size) }
    }
    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        unsafe { System.dealloc(ptr, layout) }
    }
}
#[global_allocator]
#[cfg(feature = "allocation-counts")]
static ALLOCATOR: Counting = Counting;

